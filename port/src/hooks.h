// Native overrides for ROM routines.
//
// A hook replaces the routine starting at a given ROM address. When execution
// reaches that address (by call, jp, rst or fallthrough), the interpreter runs
// the hook instead of the original instructions.
//
// On entry the CPU state is exactly what the original routine would see: the
// registers, and the caller's return address on top of the stack. By default
// the dispatcher performs the routine's final `ret` after the hook returns.
// Hooks registered with HOOK_MANUAL_RET must set gb->cpu.pc themselves (for
// routines that end in a jump rather than a ret).
#ifndef HOOKS_H
#define HOOKS_H

#include "gb.h"

typedef void (*HookFn)(GB *gb);

enum {
	HOOK_MANUAL_RET = 1 << 0,
};

typedef struct {
	const char *name; // symbol name from the disassembly
	int bank;
	uint16_t addr;
	HookFn fn;
	unsigned flags;
	unsigned clobbers; // registers (R_* in ported.h) the difftest ignores
	bool enabled;
	uint64_t calls;
} Hook;

// Load the rgblink .sym file so hooks can be looked up by label.
bool sym_load(const char *path);
// Returns false if the symbol is unknown.
bool sym_lookup(const char *name, int *bank, uint16_t *addr);
// Name of the label at or before an address (for debugging); NULL if none.
const char *sym_name_at(int bank, uint16_t addr);

void hooks_init(GB *gb);
// Register a hook by symbol name. Returns false if the symbol isn't found.
bool hook_register(const char *name, HookFn fn, unsigned flags, unsigned clobbers);
// Look up the hook for the current PC, or NULL. Fast path for the interpreter.
Hook *hook_find(GB *gb, uint16_t pc);
// Same, but ignores whether hooks are enabled (used by the difftest).
Hook *hook_find_any(GB *gb, uint16_t pc);
int hook_count(void);
Hook *hook_get(int i);
// Disable all hooks (pure interpreter), or re-enable them.
void hooks_set_enabled(bool enabled);

// Generated by the build from port/src/ported/*.c (see docs/PORTING.md).
void ported_register_all(void);

#endif
